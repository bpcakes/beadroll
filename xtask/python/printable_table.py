"""Write crates/beadroll-core/src/text/printable.rs: the code points CPython's str.isprintable() refuses,
which repr() escapes (docs/RUST-PORT.md §5 row 11). Run from the repository root with the Python the
differential tests use:

    python3 xtask/python/printable_table.py > crates/beadroll-core/src/text/printable.rs

Standard library only."""
import unicodedata


def ranges():
    out, start = [], None
    for code in range(0x110000):
        printable = chr(code).isprintable()
        if not printable and start is None:
            start = code
        elif printable and start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    found = ranges()
    print(f"//! Non-printable code points escaped by `repr()` (Unicode {unicodedata.unidata_version}).")
    print("//! Generated by `xtask/python/printable_table.py`; do not edit. Provenance: `docs/RUST-PORT.md` §4.2.")
    print()
    print("/// Inclusive ranges, in order.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) const NON_PRINTABLE: [(u32, u32); {len(found)}] = [")
    for at in range(0, len(found), 6):
        print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in found[at:at + 6]))
    print("];")


if __name__ == "__main__":
    main()
